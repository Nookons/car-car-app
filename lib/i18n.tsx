const DICT: Record<Lang, Record<Key, string>> = { ru, pl, en, uk };

const STORAGE = "carcar.lang";

const I18nContext = React.createContext<{
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key) => string;
} | null>(null);

function detectLang(): Lang {
  if (typeof window === "undefined") return "ru";
  const saved = localStorage.getItem(STORAGE) as Lang | null;
  if (saved && saved in DICT) return saved;
  const code = (window.Telegram?.WebApp as { initDataUnsafe?: { user?: { language_code?: string } } })
    ?.initDataUnsafe?.user?.language_code;
  const browser = navigator.language.slice(0, 2);
  const candidate = (code ?? browser).toLowerCase();
  if (candidate === "pl") return "pl";
  if (candidate === "en") return "en";
  if (candidate === "uk") return "uk";
  return "ru";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>("ru");

  React.useEffect(() => {
    setLangState(detectLang());
  }, []);

  const setLang = React.useCallback((next: Lang) => {
    setLangState(next);
    localStorage.setItem(STORAGE, next);
    document.documentElement.lang = next;
  }, []);

  const t = React.useCallback((key: Key) => DICT[lang][key] ?? ru[key], [lang]);

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = React.useContext(I18nContext);
  if (!ctx) throw new Error("useI18n вне I18nProvider");
  return ctx;
}

export function labelFor(
  t: (key: Key) => string,
  group: "fuel" | "gearbox" | "body" | "drive" | "condition",
  value: string | null | undefined,
): string {
  if (!value) return "";
  const key = `${group}.${value}` as Key;
  return key in ru ? t(key) : value;
}
